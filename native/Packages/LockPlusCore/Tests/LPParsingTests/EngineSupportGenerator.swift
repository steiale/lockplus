/// The EngineSupport generator (DESIGN §8.2 "How EngineSupport is generated").
///
/// Step 1+2 (extract openvpn3's lists, empirical [7b] touch test) run in the spike tool
/// `native/spike/s13-s8/host/gen_engine_support.py` against the pinned openvpn3 and write
/// `native/spike/s13-s8/results/engine-support.csv`. Step 3 is this generator: it turns that CSV plus the reviewed
/// native additions into `Sources/LPParsing/OpenVPN/OVPNEngineSupport.generated.swift`.
///
/// Invocation (regenerate and overwrite the committed file):
///
///     cd native/Packages/LockPlusCore
///     LP_REGEN_ENGINE_SUPPORT=1 swift test --scratch-path "$LP_BUILD_ROOT/spm/LockPlusCore" --filter EngineSupportTests
///
/// Without the variable the test regenerates in memory and fails on any difference from the committed file, so a
/// changed CSV (an openvpn3 bump) can't silently change the classification.
enum EngineSupportGenerator {
    static let packageRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
    static let repoRoot = packageRoot.deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
    static let csvURL = repoRoot.appending(path: "native/spike/s13-s8/results/engine-support.csv")
    static let outputURL = packageRoot.appending(path: "Sources/LPParsing/OpenVPN/OVPNEngineSupport.generated.swift")

    /// The variant that defines the table entry; the others are conditional rules applied by the normalizer.
    static let primaryVariant: [String: String] = [
        "tls-client": "tls-client+pull (pair, no client)", "pull": "pull+tls-client (pair, no client)",
        "http-proxy-option": "http-proxy-option + http-proxy (tcp)",
        "http-proxy-user-pass": "<http-proxy-user-pass> + http-proxy (tcp)",
        "http-proxy": "http-proxy (proto tcp)", "ping": "ping (no keepalive)", "ping-restart": "ping-restart (no keepalive)",
        "dev": "dev tun", "setenv": "setenv UV_ID",
    ]

    /// Reviewed native additions to the allowlist (DESIGN §8.2: "add client-cert-not-required and sni"). Each entry
    /// names the CSV row that evidences it and the class it gets.
    static let additions: [(name: String, csvCase: String, swiftValue: String, note: String)] = [
        ("client-cert-not-required", "[ov3-only] client-cert-not-required", ".mapped",
         "S13: accepted, no warning; inert locally"),
        ("sni", "[ov3-only] sni", ".mapped",
         "S13 probed it without an argument (\"must have at least 1 arguments\"); honoured with one (RESULTS-S13-S8 A1)"),
    ]

    struct Row { var fields: [String: String] }

    static func parseCSV(_ text: String) -> [Row] {
        var records: [[String]] = []
        var field = "", record: [String] = [], quoted = false
        var it = Array(text.unicodeScalars)[...]
        while let c = it.popFirst() {
            if quoted {
                if c == "\"" {
                    if it.first == "\"" { field.unicodeScalars.append("\""); it = it.dropFirst() } else { quoted = false }
                } else {
                    field.unicodeScalars.append(c)
                }
            } else if c == "\"" {
                quoted = true
            } else if c == "," {
                record.append(field); field = ""
            } else if c == "\n" {
                record.append(field); field = ""
                records.append(record); record = []
            } else if c != "\r" {
                field.unicodeScalars.append(c)
            }
        }
        if !field.isEmpty || !record.isEmpty { record.append(field); records.append(record) }
        guard let header = records.first else { return [] }
        return records.dropFirst().map { r in Row(fields: Dictionary(uniqueKeysWithValues: zip(header, r + Array(repeating: "", count: max(0, header.count - r.count))))) }
    }

    static func swiftString(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    static func generate(csv: String) throws -> String {
        let rows = parseCSV(csv)
        var per: [String: [Row]] = [:]
        for r in rows where r.fields["go_allowlist"] == "yes" {
            per[r.fields["directive"]!, default: []].append(r)
        }
        var lines: [String] = [
            "// GENERATED by the EngineSupport generator (Tests/LPParsingTests/EngineSupportGenerator.swift). DO NOT EDIT.",
            "// Input: native/spike/s13-s8/results/engine-support.csv (gen_engine_support.py, spike S13 run) + reviewed additions.",
            "// openvpn3 release/3.11.8 (4f3bdef7), OpenSSL 3.5.9. Source lists: openvpn/client/cliopt.hpp.",
            "// Regenerate: cd native/Packages/LockPlusCore &&",
            "//   LP_REGEN_ENGINE_SUPPORT=1 swift test --scratch-path \"$LP_BUILD_ROOT/spm/LockPlusCore\" --filter EngineSupportTests",
            "",
            "public enum OVPNEngineSupport {",
            "    public static let openvpn3Tag = \"release/3.11.8\"",
            "    public static let table: [String: OVPNEngineClass] = [",
        ]
        var entries: [(String, String)] = []
        for (name, xs) in per {
            let main = xs.first { $0.fields["case"] == primaryVariant[name] } ?? xs[0]
            let ec = main.fields["engine_class"]!, er = main.fields["engine_reason"]!, cat = main.fields["category"]!
            let value: String
            switch ec {
            case "mapped": value = ".mapped"
            case "ignoredSilent": value = ".ignoredSilent"
            case "ignoredWarn": value = ".ignoredWarn(\(swiftString(cat)))"
            case "dropped": value = ".dropped(\(swiftString(er)))"
            default: value = ".unsupported(\(swiftString(er)))"
            }
            let comment = xs.count > 1 ? "  // " + xs.map { "\($0.fields["case"]!): \($0.fields["empirical_class"]!)" }.joined(separator: "; ") : ""
            entries.append((name, "        \(swiftString(name)): \(value),\(comment)"))
        }
        for a in additions {
            guard rows.contains(where: { $0.fields["case"] == a.csvCase }) else {
                throw GeneratorError.missingEvidence(a.csvCase)
            }
            entries.append((a.name, "        \(swiftString(a.name)): \(a.swiftValue),  // native addition: \(a.note)"))
        }
        lines += entries.sorted { $0.0 < $1.0 }.map(\.1)
        lines += ["    ]", "}", ""]
        return lines.joined(separator: "\n")
    }

    enum GeneratorError: Error { case missingEvidence(String) }
}

@Suite("EngineSupport")
struct EngineSupportTests {
    @Test func committedTableEqualsRegenerated() throws {
        let csv = try String(contentsOf: EngineSupportGenerator.csvURL, encoding: .utf8)
        let generated = try EngineSupportGenerator.generate(csv: csv)
        if ProcessInfo.processInfo.environment["LP_REGEN_ENGINE_SUPPORT"] == "1" {
            try generated.write(to: EngineSupportGenerator.outputURL, atomically: true, encoding: .utf8)
        }
        let committed = try String(contentsOf: EngineSupportGenerator.outputURL, encoding: .utf8)
        #expect(committed == generated, "OVPNEngineSupport.generated.swift is stale: regenerate (see EngineSupportGenerator)")
    }

    @Test func tableCoversExactlyTheAllowlist() {
        #expect(Set(OVPNEngineSupport.table.keys) == OVPNAllowlist.keys)
    }

    @Test func firstRunCounts() {
        // S13 first run over the 133 Go allowlist directives: 67 mapped, 38 ignoredWarn, 9 ignoredSilent,
        // 14 dropped, 5 unsupported; plus the 2 native additions (mapped).
        var c: [String: Int] = [:]
        for (_, v) in OVPNEngineSupport.table {
            switch v {
            case .mapped: c["mapped", default: 0] += 1
            case .ignoredWarn: c["warn", default: 0] += 1
            case .ignoredSilent: c["silent", default: 0] += 1
            case .dropped: c["dropped", default: 0] += 1
            case .unsupported: c["unsupported", default: 0] += 1
            }
        }
        #expect(c == ["mapped": 69, "warn": 38, "silent": 9, "dropped": 14, "unsupported": 5])
    }

    @Test func fatalDirectivesHandled() {
        for n in ["rport", "proto-force", "socks-proxy", "fragment", "pkcs12"] {
            guard case .unsupported = OVPNEngineSupport.table[n] else { Issue.record("\(n) not unsupported"); continue }
        }
        for n in ["route-ipv6-gateway", "register-dns", "dhcp-renew", "dhcp-release", "dhcp-pre-release", "tap-sleep",
                  "dns-updown", "verify-hash", "ping-timer-rem", "ping-exit", "topology", "route-gateway", "dh", "block-outside-dns"] {
            guard case .dropped = OVPNEngineSupport.table[n] else { Issue.record("\(n) not dropped"); continue }
        }
        #expect(OVPNEngineSupport.table["keepalive"] == .mapped)
        #expect(OVPNEngineSupport.table["remote-cert-tls"] == .mapped)
        #expect(OVPNEngineSupport.table["verb"] == .ignoredSilent)
    }

    /// Every directive the engine ignores or drops has a reviewed reason; none falls through to the fail-safe default,
    /// and that default is not harmless. A regenerated table with a new key fails here until someone classifies it.
    @Test func everyIgnoredEngineDirectiveHasAnExplicitReason() {
        #expect(!OVPNNormalizer.ignoredReason("some-future-option").isHarmlessWhenIgnored)
        #expect(OVPNNormalizer.ignoredReason("some-future-option") == .engineIgnores)
        for (name, cls) in OVPNEngineSupport.table {
            switch cls {
            case .ignoredWarn, .ignoredSilent, .dropped:
                #expect(OVPNNormalizer.ignoredReason(name) != .engineIgnores, "\(name) falls through to the default reason")
            case .mapped, .unsupported: break
            }
        }
        for name in ["reneg-bytes", "reneg-pkts", "replay-window", "data-ciphers", "ncp-ciphers", "data-ciphers-fallback"] {
            #expect(!OVPNNormalizer.ignoredReason(name).isHarmlessWhenIgnored, "\(name) must be not-applied")
        }
        for name in ["tun-ipv6", "disable-occ", "route-delay", "mtu-disc", "link-mtu", "tun-mtu-extra", "allow-recursive-routing",
                     "disable-dco", "allow-pull-fqdn", "tls-version-max", "ping-exit", "route-gateway"] {
            #expect(OVPNNormalizer.ignoredReason(name).isHarmlessWhenIgnored, "\(name) should be harmless")
        }
    }

    @Test func allowCompressionNoOrBareIsNotApplied_asymAndYesAreHarmless() {
        #expect(OVPNNormalizer.ignoredReason("allow-compression", args: []) == .compressionNotEnforced)
        #expect(OVPNNormalizer.ignoredReason("allow-compression", args: ["no"]) == .compressionNotEnforced)
        #expect(!OVPNNormalizer.ignoredReason("allow-compression", args: ["no"]).isHarmlessWhenIgnored)
        for a in ["NO", "none", "Yes"] {   // unreviewed values fail safe
            #expect(!OVPNNormalizer.ignoredReason("allow-compression", args: [a]).isHarmlessWhenIgnored)
        }
        for a in ["asym", "yes"] {
            #expect(OVPNNormalizer.ignoredReason("allow-compression", args: [a]) == .compressionPolicyManaged)
            #expect(OVPNNormalizer.ignoredReason("allow-compression", args: [a]).isHarmlessWhenIgnored)
        }
    }

    @Test func plainTextSplitsNotAppliedFromNotNeeded() throws {
        let r = ImportReport(items: [
            ImportReportItem(.ignored, line: 3, directive: "persist-tun", .persistenceNotNeeded),
            ImportReportItem(.ignored, line: 4, directive: "data-ciphers", .cipherListNotApplied),
            ImportReportItem(.ignored, line: 5, directive: "verify-hash", .verifyHashNotSupported)])
        let t = r.plainText()
        #expect(t.contains("Not applied:\n  line 4 `data-ciphers`"))
        #expect(t.contains("line 5 `verify-hash`"))
        #expect(t.contains("Not needed:\n  line 3 `persist-tun`"))
        #expect(!t.contains("Will be ignored"))
        let applied = try #require(t.range(of: "Not applied"))
        let needed = try #require(t.range(of: "Not needed:"))
        #expect(applied.lowerBound < needed.lowerBound)
        #expect(!t[needed.upperBound...].contains("data-ciphers"))
    }

    @Test func realProfileDirectivesLandInTheRightGroup() {
        let text = "client\nremote vpn.example.com 1194\nallow-compression no\ndata-ciphers AES-256-GCM\nreneg-bytes 1000\ntun-ipv6\nping-exit 60\n"
        let items = OVPNImporter.importProfile(Array(text.utf8)).report.items(in: .ignored)
        func item(_ d: String) -> ImportReportItem? { items.first { $0.directive == d } }
        #expect(item("allow-compression")?.isNotApplied == true)
        #expect(item("data-ciphers")?.isNotApplied == true)
        #expect(item("reneg-bytes")?.isNotApplied == true)
        #expect(item("tun-ipv6")?.isHarmlessIgnored == true)
        #expect(item("ping-exit")?.isHarmlessIgnored == true)
    }
}
